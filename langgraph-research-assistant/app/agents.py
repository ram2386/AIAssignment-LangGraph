# 3. Wikipedia Retrieval Agent
# ---------------------------------------------------------------------------
async def wikipedia_retrieval_agent(state: ResearchState) -> dict[str, Any]:
    """Retrieve encyclopedia articles using Wikipedia MCP tool based on research plan.

    LangGraph Concept: Specialized Retrieval Node (Branch 2)
    - Runs in parallel with DuckDuckGo agent.
    - Queries Wikipedia MCP tool for conceptual / background articles.
    - Normalizes results into consistent schema: {source, query, title, url, content}.
    """
    plan = state.get("research_plan", [])
    question = state.get("question", "")
    retry_count = state.get("retry_count", 0)

    logger.info(f"[Wikipedia] Searching encyclopedia (attempt {retry_count + 1})...")

    # Select queries: adapt on retry or extract core concept
    queries_to_run: list[str] = []
    if retry_count > 0:
        # Simplify to base keywords on retry
        cleaned = re.sub(r"(?i)\b(what|how|why|is|are|the|of|for|in|to)\b", "", question).strip()
        queries_to_run = [cleaned if cleaned else question]
    elif len(plan) >= 2:
        # Pick 2 complementary queries from plan
        queries_to_run = [plan[0], plan[-1]]
    elif plan:
        queries_to_run = [plan[0]]
    else:
        queries_to_run = [question]

    raw_items: list[dict[str, Any]] = []
    errors: list[str] = []

    try:
        tools = await load_research_tools()
        wiki_tool: BaseTool | None = tools.get("wikipedia")

        if wiki_tool is not None:
            for q in queries_to_run:
                try:
                    logger.debug(f"[Wikipedia] Invoking MCP tool for query: '{q}'")
                    result = await wiki_tool.ainvoke({"query": q, "max_results": 2})
                    parsed_records = parse_mcp_content(result, q)
                    raw_items.extend(parsed_records)
                except Exception as tool_exc:
                    err_msg = f"Wikipedia MCP tool query '{q}' failed: {tool_exc}"
                    logger.warning(f"[Wikipedia] {err_msg}")
                    errors.append(err_msg)
        else:
            errors.append("Wikipedia MCP tool was not found in loaded tools.")
    except Exception as mcp_exc:
        err_msg = f"Failed to connect to Wikipedia MCP server: {mcp_exc}"
        logger.error(f"[Wikipedia] {err_msg}")
        errors.append(err_msg)

    # Normalize results into expected schema
    normalized_results: list[dict[str, str]] = []
    for item in raw_items:
        title = item.get("title") or "Wikipedia Article"
        content = item.get("content") or item.get("summary") or ""
        url = item.get("url") or ""
        q = item.get("query") or question

        if content.strip():
            normalized_results.append(
                {
                    "source": "wikipedia",
                    "query": q,
                    "title": title,
                    "url": url,
                    "content": content,
                }
            )

    logger.info(f"[Wikipedia] Retrieved {len(normalized_results)} valid records.")
    return {
        "wikipedia_results": normalized_results,
        "search_results": normalized_results,
        "errors": errors,
    }


# ---------------------------------------------------------------------------
# 4. Evaluation & Retry Node (Fan-in Join Point)
# ---------------------------------------------------------------------------
async def evaluate_retrieval(state: ResearchState) -> dict[str, Any]:
    """Examine retrieved results and manage retry state if needed.

    LangGraph Concept: Fan-in Barrier & Conditional Transition
    - Both parallel branches (DuckDuckGo and Wikipedia) merge into this node.
    - Determines if useful content has been collected.
    - If empty and retry budget remains, increments `retry_count`.
    """
    search_results = state.get("search_results", [])
    retry_count = state.get("retry_count", 0)

    # Filter out empty or error results to determine true content availability
    valid_results = [
        r for r in search_results
        if r.get("content") and not r.get("title", "").lower().startswith("search error")
    ]

    has_results = len(valid_results) > 0
    max_retries = int(os.getenv("MAX_RETRIES", "2"))

    if not has_results and retry_count < max_retries:
        next_retry = retry_count + 1
        logger.warning(
            f"[Retry Check] No search results found. Scheduling retry {next_retry}/{max_retries}..."
        )
        return {"retry_count": next_retry}

    if not has_results and retry_count >= max_retries:
        logger.warning(
            f"[Retry Check] Maximum retry limit ({max_retries}) reached. Continuing with available context."
        )

    logger.info(f"[Retry Check] Found {len(valid_results)} usable records. Proceeding to summarizer.")
    return {}


