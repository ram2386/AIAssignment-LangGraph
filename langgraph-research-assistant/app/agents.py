# 2. DuckDuckGo Retrieval Agent
# ---------------------------------------------------------------------------
async def duckduckgo_retrieval_agent(state: ResearchState) -> dict[str, Any]:
    """Execute live web searches using DuckDuckGo MCP tool based on research plan.

    LangGraph Concept: Specialized Retrieval Node (Branch 1)
    - Reads `research_plan` and `retry_count`.
    - Selects targeted web search queries.
    - Invokes the MCP tool asynchronously.
    - Normalizes results into consistent schema: {source, query, title, url, content}.
    """
    plan = state.get("research_plan", [])
    question = state.get("question", "")
    retry_count = state.get("retry_count", 0)

    logger.info(f"[DuckDuckGo] Searching live web (attempt {retry_count + 1})...")

    # Select queries: adapt if this is a retry attempt
    queries_to_run: list[str] = []
    if retry_count > 0:
        # Broaden search on retry
        queries_to_run = [f"{question} overview summary", f"{question} documentation"]
    elif plan:
        # Pick top 2 queries from plan
        queries_to_run = plan[:2]
    else:
        queries_to_run = [question]

    raw_items: list[dict[str, Any]] = []
    errors: list[str] = []

    try:
        tools = await load_research_tools()
        ddg_tool: BaseTool | None = tools.get("duckduckgo")

        if ddg_tool is not None:
            for q in queries_to_run:
                try:
                    logger.debug(f"[DuckDuckGo] Invoking MCP tool for query: '{q}'")
                    result = await ddg_tool.ainvoke({"query": q, "max_results": 3})
                    parsed_records = parse_mcp_content(result, q)
                    raw_items.extend(parsed_records)
                except Exception as tool_exc:
                    err_msg = f"DuckDuckGo MCP tool query '{q}' failed: {tool_exc}"
                    logger.warning(f"[DuckDuckGo] {err_msg}")
                    errors.append(err_msg)
        else:
            errors.append("DuckDuckGo MCP tool was not found in loaded tools.")
    except Exception as mcp_exc:
        err_msg = f"Failed to connect to DuckDuckGo MCP server: {mcp_exc}"
        logger.error(f"[DuckDuckGo] {err_msg}")
        errors.append(err_msg)

    # Normalize results into expected schema
    normalized_results: list[dict[str, str]] = []
    for item in raw_items:
        title = item.get("title") or "Web Search Result"
        content = item.get("content") or item.get("body") or ""
        url = item.get("url") or item.get("href") or ""
        q = item.get("query") or question

        if content.strip():
            normalized_results.append(
                {
                    "source": "duckduckgo",
                    "query": q,
                    "title": title,
                    "url": url,
                    "content": content,
                }
            )

    logger.info(f"[DuckDuckGo] Retrieved {len(normalized_results)} valid records.")
    return {
        "duckduckgo_results": normalized_results,
        "search_results": normalized_results,
        "errors": errors,
    }


