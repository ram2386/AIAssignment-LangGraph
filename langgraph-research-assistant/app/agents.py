"""Specialized Agent implementations for the Multi-Agent Research Assistant.

LangGraph Concept: Specialized Agent Nodes
------------------------------------------
In LangGraph, each agent is a Python function (node) that receives the current
`ResearchState` and returns a dictionary of state updates.

Rather than relying on a single monolithic LLM call:
1. Planning Agent decomposes the user's question into targeted sub-tasks.
2. DuckDuckGo Agent queries live web search tools via MCP.
3. Wikipedia Agent queries encyclopedic tools via MCP in parallel.
4. Summarizer Agent synthesizes and contrasts evidence across sources.
5. Final Answer Agent compiles a cited, verified final response.
"""

import json
import logging
import os
import re
from typing import Any

from pydantic import BaseModel, Field
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_core.tools import BaseTool

from app.state import ResearchState
from app.tools import load_research_tools

logger = logging.getLogger("research_assistant.agents")


# ---------------------------------------------------------------------------
# Structured Output Schemas
# ---------------------------------------------------------------------------
class ResearchPlanOutput(BaseModel):
    """Structured research plan generated by the Planning Agent."""

    research_plan: list[str] = Field(
        description="A list of 3 to 5 specific, distinct search tasks or queries to research the question."
    )


# ---------------------------------------------------------------------------
# LLM Provider Factory
# ---------------------------------------------------------------------------
def get_llm():
    """Initialize and return the configured LangChain ChatModel.

    Checks `LLM_PROVIDER` in environment:
    - 'gemini' (default): Uses `langchain-google-genai` ChatGoogleGenerativeAI.
    - 'groq': Uses ChatGroq if installed and configured.
    - 'mistral': Uses ChatMistralAI if installed and configured.
    - If no valid API key is present or LLM_PROVIDER is 'mock', returns None
      to enable graceful heuristic fallback for offline testing.
    """
    provider = os.getenv("LLM_PROVIDER", "gemini").lower()
    google_key = os.getenv("GOOGLE_API_KEY", "")

    if provider == "gemini":
        if not google_key or "your_api_key_here" in google_key:
            logger.info("No active GOOGLE_API_KEY found; operating in graceful mock/offline mode.")
            return None
        from langchain_google_genai import ChatGoogleGenerativeAI

        model_name = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
        return ChatGoogleGenerativeAI(
            model=model_name,
            google_api_key=google_key,
            temperature=0.2,
        )

    if provider == "groq":
        groq_key = os.getenv("GROQ_API_KEY", "")
        if not groq_key or "your_api_key_here" in groq_key:
            return None
        try:
            from langchain_groq import ChatGroq

            return ChatGroq(
                model=os.getenv("GROQ_MODEL", "llama-3.3-70b-versatile"),
                api_key=groq_key,
                temperature=0.2,
            )
        except ImportError:
            logger.warning("langchain-groq not installed. Falling back to offline mode.")
            return None

    return None


# ---------------------------------------------------------------------------
# 1. Planning Agent
# ---------------------------------------------------------------------------
async def planning_agent(state: ResearchState) -> dict[str, Any]:
    """Analyze the user question and produce a structured research plan.

    LangGraph Concept: Planning Node
    - Receives `question` from state.
    - Uses structured LLM output to produce 3-5 specific sub-queries.
    - Updates `state['research_plan']`.
    """
    question = state.get("question", "").strip()
    logger.info(f"[Planner] Creating research plan for: '{question}'")

    llm = get_llm()
    plan: list[str] = []

    if llm is not None:
        try:
            # Try structured output first
            structured_llm = llm.with_structured_output(ResearchPlanOutput)
            prompt = (
                f"You are an expert research planner. Deconstruct the following question "
                f"into 3 to 4 distinct, highly focused research tasks or search queries that "
                f"cover definitions, core mechanisms, benefits/trade-offs, and practical comparisons.\n\n"
                f"Question: {question}"
            )
            result = await structured_llm.ainvoke(prompt)
            if result and getattr(result, "research_plan", None):
                plan = [p.strip() for p in result.research_plan if p.strip()]
        except Exception as exc:
            logger.warning(f"[Planner] Structured LLM call failed: {exc}. Trying raw completion.")
            try:
                raw_res = await llm.ainvoke(
                    f"Create a 3-point research plan for: '{question}'. "
                    f"Return ONLY a JSON list of strings, for example: [\"query 1\", \"query 2\", \"query 3\"]"
                )
                content = raw_res.content if hasattr(raw_res, "content") else str(raw_res)
                # Extract json list
                match = re.search(r"\[.*\]", content, re.DOTALL)
                if match:
                    plan = json.loads(match.group(0))
            except Exception as raw_exc:
                logger.warning(f"[Planner] Raw completion also failed: {raw_exc}.")

    # Deterministic fallback plan if LLM not configured or offline
    if not plan:
        plan = [
            f"Overview and definition of {question}",
            f"Key features and technical architecture of {question}",
            f"Advantages, limitations, and use cases of {question}",
        ]

    logger.info(f"[Planner] Generated {len(plan)} research tasks: {plan}")
    return {"research_plan": plan}


def parse_mcp_content(raw_value: Any, query: str) -> list[dict[str, Any]]:
    """Parse MCP tool result into structured dictionary records."""
    records: list[dict[str, Any]] = []

    def _process_text(text: str):
        try:
            parsed = json.loads(text)
            if isinstance(parsed, list):
                for p in parsed:
                    if isinstance(p, dict):
                        records.append({"query": query, **p})
                    else:
                        records.append({"query": query, "content": str(p)})
            elif isinstance(parsed, dict):
                records.append({"query": query, **parsed})
            else:
                records.append({"query": query, "content": str(parsed)})
        except Exception:
            records.append({"query": query, "content": text})

    if isinstance(raw_value, list):
        for item in raw_value:
            if isinstance(item, dict):
                if "text" in item:
                    _process_text(item["text"])
                else:
                    records.append({"query": query, **item})
            elif hasattr(item, "text"):
                _process_text(getattr(item, "text", ""))
            elif isinstance(item, str):
                _process_text(item)
    elif isinstance(raw_value, dict):
        if "text" in raw_value:
            _process_text(raw_value["text"])
        else:
            records.append({"query": query, **raw_value})
    elif isinstance(raw_value, str):
        _process_text(raw_value)

    return records


